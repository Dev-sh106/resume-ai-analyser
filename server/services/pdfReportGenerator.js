/**
 * PDF Report Generator Service for Node.js using PDFKit.
 * Replaces Python ReportLab to generate downloadable ATS Audit Report PDFs.
 */

const PDFDocument = require("pdfkit");

class PDFReportGenerator {
  static generateReportBuffer(analysisResult, filename = "Resume") {
    return new Promise((resolve, reject) => {
      try {
        const doc = new PDFDocument({ margin: 50, size: "A4" });
        const buffers = [];

        doc.on("data", b => buffers.push(b));
        doc.on("end", () => resolve(Buffer.concat(buffers)));

        const sc = analysisResult.scoring;

        // Title Header
        doc.fontSize(22).fillColor("#1E293B").text("ATS Resume Audit Report", { underline: false });
        doc.fontSize(11).fillColor("#64748B").text(`File: ${filename}  |  Generated by ATS Engine`, { baseline: "middle" });
        doc.moveDown(1.2);

        // Overall Score Box
        doc.rect(50, doc.y, 495, 65).fillAndStroke("#F8FAFC", "#CBD5E1");
        const boxTop = doc.y + 12;
        doc.fillColor("#0F172A").fontSize(13).text("OVERALL ATS SCORE", 65, boxTop);
        doc.fontSize(26).fillColor(sc.overallScore >= 80 ? "#16A34A" : (sc.overallScore >= 60 ? "#2563EB" : "#DC2626"))
           .text(`${sc.overallScore} / 100`, 65, boxTop + 18);
        doc.fontSize(14).fillColor("#334155").text(`Grade ${sc.grade} - ${sc.rating}`, 220, boxTop + 24);

        doc.moveDown(4.5);

        // Subscores
        doc.fontSize(14).fillColor("#1E293B").text("Subsystem Breakdown:");
        doc.moveDown(0.5);

        for (const [k, v] of Object.entries(sc.subscores)) {
          doc.fontSize(11).fillColor("#334155")
             .text(`• ${v.label}: `, { continued: true })
             .fillColor("#0F172A")
             .text(`${v.score} / ${v.max} pts (${Math.round((v.score / v.max) * 100)}%)`);
        }

        doc.moveDown(1);

        // Issues
        if (sc.criticalIssues.length > 0) {
          doc.fontSize(13).fillColor("#DC2626").text("Critical Issues (Must Fix):");
          sc.criticalIssues.forEach((c, i) => {
            doc.fontSize(10).fillColor("#991B1B").text(`${i + 1}. [${c.category}] ${c.issue}`);
            doc.fillColor("#475569").text(`   Fix: ${c.suggestion}`).moveDown(0.3);
          });
          doc.moveDown(0.8);
        }

        if (sc.warnings.length > 0) {
          doc.fontSize(13).fillColor("#D97706").text("Warnings & Optimizations:");
          sc.warnings.forEach((w, i) => {
            doc.fontSize(10).fillColor("#92400E").text(`${i + 1}. [${w.category}] ${w.issue}`);
            doc.fillColor("#475569").text(`   Fix: ${w.suggestion}`).moveDown(0.3);
          });
          doc.moveDown(0.8);
        }

        // Job Description Match
        if (analysisResult.jdMatch && analysisResult.jdMatch.hasJd) {
          doc.fontSize(13).fillColor("#2563EB").text("Job Description Alignment:");
          doc.fontSize(10).fillColor("#334155")
             .text(`Match Percentage: ${analysisResult.jdMatch.matchPercentage}%`)
             .text(`Matched Skills: ${(analysisResult.jdMatch.matchedSkills || []).slice(0, 10).join(", ") || "None"}`)
             .text(`Missing Key Skills: ${(analysisResult.jdMatch.missingSkills || []).slice(0, 10).join(", ") || "None"}`)
             .moveDown(1);
        }

        doc.end();
      } catch (err) {
        reject(err);
      }
    });
  }
}

module.exports = PDFReportGenerator;
