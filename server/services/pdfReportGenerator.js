/**
 * PDF Report Generator Service for Node.js using PDFKit.
 * Replaces Python ReportLab to generate downloadable ATS Audit Report PDFs.
 */

const PDFDocument = require("pdfkit");

class PDFReportGenerator {
  static generateReportBuffer(analysisResult, filename = "Resume") {
    return new Promise((resolve, reject) => {
      try {
        const doc = new PDFDocument({ margin: 50, size: "A4" });
        const buffers = [];

        doc.on("data", b => buffers.push(b));
        doc.on("end", () => resolve(Buffer.concat(buffers)));

        const sc = analysisResult?.scoring || {};
        const overallScore = typeof sc.overallScore === "number" ? sc.overallScore : 0;
        const grade = sc.grade || "N/A";
        const rating = sc.rating || "Evaluated";
        const subscores = sc.subscores || {};
        const criticalIssues = Array.isArray(sc.criticalIssues) ? sc.criticalIssues : [];
        const warnings = Array.isArray(sc.warnings) ? sc.warnings : [];
        const jdMatch = analysisResult?.jdMatch || {};

        // Title Header
        doc.fontSize(22).fillColor("#1E293B").text("ATS Resume Audit Report", { underline: false });
        doc.fontSize(11).fillColor("#64748B").text(`File: ${filename || "Resume"}  |  Generated by ATS Engine`, { baseline: "middle" });
        doc.moveDown(1.2);

        // Overall Score Box
        doc.rect(50, doc.y, 495, 65).fillAndStroke("#F8FAFC", "#CBD5E1");
        const boxTop = doc.y + 12;
        doc.fillColor("#0F172A").fontSize(13).text("OVERALL ATS SCORE", 65, boxTop);
        doc.fontSize(26).fillColor(overallScore >= 80 ? "#16A34A" : (overallScore >= 60 ? "#2563EB" : "#DC2626"))
           .text(`${overallScore} / 100`, 65, boxTop + 18);
        doc.fontSize(14).fillColor("#334155").text(`Grade ${grade} - ${rating}`, 220, boxTop + 24);

        doc.moveDown(4.5);

        // Subscores
        doc.fontSize(14).fillColor("#1E293B").text("Subsystem Breakdown:");
        doc.moveDown(0.5);

        for (const [k, v] of Object.entries(subscores)) {
          if (!v) continue;
          const score = typeof v.score === "number" ? v.score : 0;
          const max = typeof v.max === "number" ? v.max : 20;
          const label = v.label || k;
          doc.fontSize(11).fillColor("#334155")
             .text(`• ${label}: `, { continued: true })
             .fillColor("#0F172A")
             .text(`${score} / ${max} pts (${Math.round((score / max) * 100)}%)`);
        }

        doc.moveDown(1);

        // Issues
        if (criticalIssues.length > 0) {
          doc.fontSize(13).fillColor("#DC2626").text("Critical Issues (Must Fix):");
          criticalIssues.forEach((c, i) => {
            doc.fontSize(10).fillColor("#991B1B").text(`${i + 1}. [${c.category || "Issue"}] ${c.issue || ""}`);
            if (c.suggestion) {
              doc.fillColor("#475569").text(`   Fix: ${c.suggestion}`).moveDown(0.3);
            }
          });
          doc.moveDown(0.8);
        }

        if (warnings.length > 0) {
          doc.fontSize(13).fillColor("#D97706").text("Warnings & Optimizations:");
          warnings.forEach((w, i) => {
            doc.fontSize(10).fillColor("#92400E").text(`${i + 1}. [${w.category || "Warning"}] ${w.issue || ""}`);
            if (w.suggestion) {
              doc.fillColor("#475569").text(`   Fix: ${w.suggestion}`).moveDown(0.3);
            }
          });
          doc.moveDown(0.8);
        }

        // Job Description Match
        if (jdMatch && jdMatch.hasJd) {
          doc.fontSize(13).fillColor("#2563EB").text("Job Description Alignment:");
          doc.fontSize(10).fillColor("#334155")
             .text(`Match Percentage: ${jdMatch.matchPercentage || 0}%`)
             .text(`Matched Skills: ${(jdMatch.matchedSkills || []).slice(0, 10).join(", ") || "None"}`)
             .text(`Missing Key Skills: ${(jdMatch.missingSkills || []).slice(0, 10).join(", ") || "None"}`)
             .moveDown(1);
        }

        doc.end();
      } catch (err) {
        reject(err);
      }
    });
  }
}

module.exports = PDFReportGenerator;
